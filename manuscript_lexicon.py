    @classmethod
    def detect_domain(cls, text: str) -> str:
        scores = {k: 0 for k in cls.DOMAIN_KEYWORDS}
        for domain, keywords in cls.DOMAIN_KEYWORDS.items():
            for kw in keywords:
                scores[domain] += len(re.findall(re.escape(kw), text, re.IGNORECASE))
        best_domain = max(scores, key=scores.get)
        if scores[best_domain] >= 2:
            return best_domain
        return "general"

    @staticmethod
    def _build_arabic_pattern(word: str) -> str:
        """بناء نمط regex يطابق الكلمة العربية مع مراعاة السوابق وتنويعات الألف والياء والتاء المربوطة."""
        letters = []
        for ch in word:
            if ch in ["أ", "إ", "آ", "ا"]:
                letters.append("[أإآا]")
            elif ch in ["ى", "ي", "ئ"]:
                letters.append("[ىيئ]")
            elif ch in ["ة", "ه"]:
                letters.append("[ةه]")
            elif ch == " ":
                letters.append(r"\s+")
            else:
                letters.append(re.escape(ch))
        core_pat = "".join(letters)
        
        # السماح بالسوابق العربية الشائعة (و، فـ، بـ، كـ، لـ، بالـ، كالـ، فلـ)
        pattern = r"(?<![^\s\(\[«،؛:\-\.])([وفبكل]|وبالـ|فبالـ|بالـ|كالـ|لل)?(" + core_pat + r")(?![^\s\)\]»،؛:\-\.])"
        return pattern

    @classmethod
    def correct_text(cls, text: str, domain: str = "auto") -> Tuple[str, List[Dict[str, str]]]:
        """تطبيق التصحيحات التراثية والسياقية على النص المستخرج."""
        if not text:
            return text, []

        if domain == "auto":
            domain = cls.detect_domain(text)

        corrections_applied = []
        result_text = text

        dicts_to_apply = []
        if domain in cls.COMMON_PALEOGRAPHIC_FIXES:
            dicts_to_apply.append(cls.COMMON_PALEOGRAPHIC_FIXES[domain])
        
        for d_key, d_dict in cls.COMMON_PALEOGRAPHIC_FIXES.items():
            if d_key != domain and d_dict not in dicts_to_apply:
                dicts_to_apply.append(d_dict)

        for fix_dict in dicts_to_apply:
            sorted_keys = sorted(fix_dict.keys(), key=len, reverse=True)
            for raw_pattern in sorted_keys:
                correct_word = fix_dict[raw_pattern]
                pat = cls._build_arabic_pattern(raw_pattern)
                
                if re.search(pat, result_text):
                    matches = len(re.findall(pat, result_text))
                    
                    def _replace_match(m):
                        prefix = m.group(1) or ""
                        # إذا كانت الكلمة المصححة تبدأ بـ ال التعريف والسابقة تنتهي بـ ال
                        target = correct_word
                        if prefix in ["بالـ", "كالـ", "فبالـ", "وبالـ"] and target.startswith("ال"):
                            target = target[2:]
                        return prefix + target
                        
                    result_text = re.sub(pat, _replace_match, result_text)
                    corrections_applied.append({
                        "original": raw_pattern,
                        "corrected": correct_word,
                        "count": str(matches),
                        "domain": domain
                    })

        return result_text, corrections_applied